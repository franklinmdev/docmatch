"""The committed regional fixture: made-up Dominican comprobantes, drawn by code.

No owner's comprobante may enter a test, a fixture or a commit (`CLAUDE.md`
rule 6), so the `do` set CI scores is three comprobantes invented here: a B01
crédito fiscal to a company, a B02 consumo to nobody, whose customer cell is a
labeled absence, and the printed form of an E31 to a person. Every name,
number and amount is made up. The RNCs, the cedula and the NCFs carry check
digits and type codes python-stdnum 2.2 accepts (its `stdnum.do.rnc`,
`stdnum.do.cedula`, `stdnum.do.ncf` and `stdnum.luhn` sources, read
2026-10-23), because a later gate rule checks exactly that, but a valid
number can still be someone's: the bases below were picked by hand and the
cedula's `000` office prefix was chosen as one no office issues (unverified).
The amounts are not computed at any tax rate; the fixture states no fiscal
rule.

Each image is drawn with Pillow 12.3's built-in bitmap font,
`ImageFont.load_default_imagefont()`, which needs no FreeType and draws the
same pixels everywhere, then scaled up by nearest neighbour so the glyphs stay
sharp. The PNG bytes still depend on the zlib that compressed them, so the
images are pinned by the manifest written beside them, not regenerated by
the tests. The saved run beside the set is made-up readings, never a backend's:
one comprobante read right with a value of a fieldtype the set does not cover
and a line item, one with its NCF misread, one with its tax left unread.

Regenerate with `uv run python -m docmatch.evals.regional_fixture`.
"""

import json
import sys
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
