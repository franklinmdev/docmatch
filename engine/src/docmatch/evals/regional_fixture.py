"""Each regional fieldtype and the caption the drawn comprobante prints it under."""


def _lines(comprobante: Comprobante) -> list[str]:
    labels = comprobante.labels
    lines = [
        labels["vendor_name"],
        f"RNC: {labels['vendor_tax_id']}",
        "",
        f"Fecha: {labels['date_issue']}",
        f"NCF: {labels['document_id']}",
    ]
    if labels["customer_tax_id"]:
        lines += [
            f"Cliente: {comprobante.customer_name}",
            f"RNC/Cedula: {labels['customer_tax_id']}",
        ]
    else:
        lines.append("Consumidor final")
    printed = [
        f"{caption:<16}{labels[each]}" for each, caption in PRINTED if labels[each]
    ]
    return [
        *lines,
        "",
        f"Subtotal:      {labels['amount_total_net']}",
        f"ITBIS:         {labels['amount_total_tax']}",
        *printed,
        f"Total RD$:     {labels['amount_total_gross']}",
    ]


def draw(comprobante: Comprobante) -> Image.Image:
    """The comprobante as a grayscale page, black text on white."""
    font = ImageFont.load_default_imagefont()
    lines = _lines(comprobante)
    small = Image.new("L", (6 * 36 + 16, 12 * len(lines) + 16), 255)
    pen = ImageDraw.Draw(small)
    for number, line in enumerate(lines):
        pen.text((8, 8 + 12 * number), line, fill=0, font=font)
    return small.resize(
        (small.width * SCALE, small.height * SCALE), Image.Resampling.NEAREST
    )


def labels_csv() -> str:
    """The set's labels as `labels.csv` holds them, one row per comprobante."""
    header = ",".join((FILENAME, *COVERAGE, PAPER))
    rows = (
        ",".join(
            (
                each.filename,
                *(_cell(each.labels[fieldtype]) for fieldtype in COVERAGE),
                each.paper,
            )
        )
        for each in COMPROBANTES
    )
    return "\n".join((header, *rows)) + "\n"


def filing_csv() -> str:
    """The set's filing annotation as `filing.csv` holds it."""
    header = ",".join((FILENAME, *FILING_COLUMNS))
    rows = (f"{each.filename},{each.filing}" for each in COMPROBANTES)
    return "\n".join((header, *rows)) + "\n"


def _cell(value: str) -> str:
    return f'"{value}"' if "," in value else value


def write_set(directory: Path) -> Manifest:
    """Draw every comprobante into `directory`, with its labels and manifest."""
    directory.mkdir(parents=True, exist_ok=True)
    for each in COMPROBANTES:
        draw(each).save(directory / each.filename, "PNG")
    labels = labels_csv().encode()
    (directory / LABELS_FILE).write_bytes(labels)
    filing = filing_csv().encode()
    (directory / FILING_FILE).write_bytes(filing)
    manifest = Manifest(
        split="paper",
        seed=0,
        source="synthetic",
        size=len(COMPROBANTES),
        document_ids=tuple(each.filename for each in COMPROBANTES),
        digests={
            each.filename: digest((directory / each.filename).read_bytes())
            for each in COMPROBANTES
        },
        region=REGION,
        coverage=COVERAGE,
        files={LABELS_FILE: digest(labels), FILING_FILE: digest(filing)},
        reporter=REPORTER,
    )
    write(manifest, directory / MANIFEST_FILE)
    return manifest


def readings() -> dict[str, dict[str, object]]:
    """The saved run's made-up readings, keyed by filename."""
    by_name = {each.filename: dict(each.labels) for each in COMPROBANTES}
    right = by_name["do0001.png"]
    misread = by_name["do0002.png"]
    untaxed = by_name["do0003.png"]
    right["vendor_email"] = "ventas@example.do"
    misread["document_id"] = "B0200001238"
    del untaxed["amount_total_tax"]
    by_name["do0006.png"]["document_id"] = "E310000000019"
    fields = {
        name: {key: value or None for key, value in labels.items()}
        for name, labels in by_name.items()
    }
    return {
        name: {"fields": values}
        | (
            {
                "line_items": [
                    {
                        "line_item_description": "Cemento gris",
                        "line_item_quantity": "10",
                    }
                ]
            }
            if name == "do0001.png"
            else {}
        )
        for name, values in fields.items()
    }


def write_run(directory: Path, manifest: Manifest) -> None:
    """Save the made-up readings of the set `manifest` pins as a run."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / PREDICTIONS_FILE).write_text(
        json.dumps(readings(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    record = {"backend": "gemini", "requested_model": "synthetic-001", "region": REGION}
    (directory / RECORD_FILE).write_text(
        json.dumps(record, indent=2) + "\n", encoding="utf-8"
    )
    write(manifest, directory / MANIFEST_FILE)


def main(directory: Path = FIXTURE) -> None:
    manifest = write_set(directory / REGION)
    write_run(directory / "run", manifest)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else FIXTURE)
