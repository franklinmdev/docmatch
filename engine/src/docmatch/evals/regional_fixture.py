from stdnum.do import rnc

from docmatch.evals.manifest import Manifest, write
from docmatch.evals.public import digest
from docmatch.evals.regional import FILENAME, LABELS_FILE, PAPER
from docmatch.evals.run import MANIFEST_FILE, PREDICTIONS_FILE, RECORD_FILE

FIXTURE = Path(__file__).parents[3] / "tests" / "evals" / "regional"
REGION = "do"
COVERAGE = (
    "vendor_name",
    "vendor_tax_id",
    "customer_tax_id",
    "document_id",
    "date_issue",
    "amount_total_net",
    "amount_total_tax",
    "amount_total_gross",
)
"""The fieldtypes the paper set covers before #225 adds the six DocILE lacks."""

SCALE = 3
"""How many pixels each pixel of the bitmap font becomes."""


def _rnc(base: str) -> str:
    return base + rnc.calc_check_digit(base)


def _cedula(base: str) -> str:
    return base + luhn.calc_check_digit(base)


@dataclass(frozen=True)
class Comprobante:
    """One made-up comprobante: its file, its labels and what it is printed on."""

    filename: str
    labels: dict[str, str]
    """Every covered fieldtype to its printed value; empty is a labeled absence."""
    paper: str
    customer_name: str = ""


